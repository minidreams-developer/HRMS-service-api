const cloudinary = require('cloudinary').v2;
const { CloudinaryStorage } = require('multer-storage-cloudinary');
const multer = require('multer');

// Configure cloudinary from env
cloudinary.config({
  cloud_name: process.env.CLOUDINARY_CLOUD_NAME,
  api_key: process.env.CLOUDINARY_API_KEY,
  api_secret: process.env.CLOUDINARY_API_SECRET,
});

/**
 * Returns a multer middleware that uploads files to Cloudinary.
 * @param {string} folder - Cloudinary folder to store uploads in
 * @param {string} fieldName - The multipart field name (default: 'images')
 * @param {number} maxCount  - Max number of files allowed (default: 10)
 */
const cloudinaryUpload = (folder = 'hrms', fieldName = 'images', maxCount = 10) => {
  const storage = new CloudinaryStorage({
    cloudinary,
    params: {
      folder,
      allowed_formats: ['jpg', 'jpeg', 'png', 'webp', 'gif'],
      // public_id is auto-generated by Cloudinary
    },
  });

  const upload = multer({
    storage,
    limits: { fileSize: 5 * 1024 * 1024 }, // 5 MB per file
  });

  return upload.array(fieldName, maxCount);
};

module.exports = { cloudinaryUpload, cloudinary };
